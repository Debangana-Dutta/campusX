"""Explain a scheduling decision from REAL data (dataset rules, the current schedule, the soft-penalty formulas,
solver status). Nothing here is generated by a model, so nothing can be invented."""
from __future__ import annotations

from collections import defaultdict
from typing import Any

from app.services.dataset.loader import Dataset
from app.services.scheduling.scoring import soft_penalties
from app.services.scheduling.solver import build_candidates


def explain_session(ds: Dataset, assign: dict, sid: str, solver_info: dict | None = None) -> dict[str, Any]:
    s, (day, p, room) = ds.sessions[sid], assign[sid]
    r, per = ds.rooms[room], ds.periods(p, ds.sessions[sid]["duration"])
    f = ds.faculty[s["faculty_id"]]
    cands, why = build_candidates(ds, sessions=[sid])
    n_slots = len({(d, st) for d, st, _ in cands[sid]})
    n_rooms = len({rm for _, _, rm in cands[sid]})
    facts: list[str] = [
        f"{sid} runs {day} {ds.raw['calendar']['periods'][p - 1]['start']} (P{p}) in {room}.",
        f"Before optimising, the hard rules leave {n_slots} possible day/period slots and {n_rooms} possible rooms for this session "
        f"(room type {', '.join(s['room_types'])}, at least {s['size']} seats"
        f"{', accessible' if s['needs_accessible'] else ''}, faculty and room availability, lunch and lab-start rules).",
        f"{room} is a {r['type'].replace('_', ' ')} with {r['capacity']} seats for {s['size']} students "
        f"({100 * s['size'] // r['capacity']}% full" + (", below the 40% target" if s["size"] / r["capacity"] < 0.4 else ", meets the 40% target") + ").",
    ]
    avoid = [pr for pr in f.get("preferences", []) if pr.get("type") == "avoid" and day in pr.get("days", ds.days)
             and any(q in pr["periods"] for q in per)]
    facts.append(f"{f['name']} asked to avoid {len(avoid)} slot(s) that overlap this session." if avoid
                 else f"{f['name']} has no 'avoid' preference on this slot.")
    if p == 1:
        facts.append("P1 (08:00) is not penalised by any soft rule; the solver uses it when it keeps groups' days compact and clash-free.")
    if 9 in per:
        facts.append("This session uses P9 (17:00), which costs 1 soft penalty point.")
    for g in s["groups"]:
        ps = sorted({q for sid2, (d2, p2, _) in assign.items() if d2 == day and g in ds.sessions[sid2]["groups"]
                     for q in range(p2, p2 + ds.sessions[sid2]["duration"])})
        gaps = sum(1 for q in range(ps[0], ps[-1] + 1) if q not in ps)
        facts.append(f"Group {g} has {len(ps)} teaching hour(s) that day (P{ps[0]}-P{ps[-1]}) with {gaps} free period(s) between classes.")
    sp = (solver_info or {})
    soft = soft_penalties(ds, assign)
    return {"session_id": sid, "facts": facts, "soft_penalties_total": soft, "solver_status": sp.get("status"),
            "note": "Every statement is computed from the dataset rules and the current schedule."}
